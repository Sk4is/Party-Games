import { PinturilloCategory } from '../types/pinturillo';

/**
 * Lienzo Loco Word Catalog
 * Visually drawable + reasonably guessable party drawing prompts.
 * Cleaned of overly abstract, obscure, or unguessable specialist terminology.
 */

export interface DrawableWord {
  id: string;
  word: string;
  category: PinturilloCategory;
  difficulty: 'FACIL' | 'NORMAL' | 'DIFICIL';
  aliases?: string[];
}

type WordEntry = string | { word: string; aliases: string[] };

function buildCategoryWords(
  cat: PinturilloCategory,
  facil: WordEntry[],
  normal: WordEntry[],
  dificil: WordEntry[]
): DrawableWord[] {
  let idx = 1;
  const list: DrawableWord[] = [];

  const addEntries = (entries: WordEntry[], diff: 'FACIL' | 'NORMAL' | 'DIFICIL') => {
    for (const item of entries) {
      if (typeof item === 'string') {
        list.push({
          id: `${cat}_${idx++}`,
          word: item.trim(),
          category: cat,
          difficulty: diff,
        });
      } else {
        list.push({
          id: `${cat}_${idx++}`,
          word: item.word.trim(),
          category: cat,
          difficulty: diff,
          aliases: item.aliases,
        });
      }
    }
  };

  addEntries(facil, 'FACIL');
  addEntries(normal, 'NORMAL');
  addEntries(dificil, 'DIFICIL');
  return list;
}

