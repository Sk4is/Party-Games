export function getRandomWordOptions(count: number = 3, usedWords: Set<string> = new Set()): DrawableWord[] {
  const available = PINTURILLO_WORDS.filter(w => !usedWords.has(w.word.toLowerCase()));
  const pool = available.length >= count ? available : PINTURILLO_WORDS;

  // Try to pick words with diverse difficulties (e.g. 1 Facil, 1 Normal, 1 Dificil)
  const facil = pool.filter(w => w.difficulty === 'FACIL');
  const normal = pool.filter(w => w.difficulty === 'NORMAL');
  const dificil = pool.filter(w => w.difficulty === 'DIFICIL');

  const selected: DrawableWord[] = [];

  const pickOne = (arr: DrawableWord[]) => {
    if (arr.length === 0) return null;
    const item = arr[Math.floor(Math.random() * arr.length)];
    return item;
  };

  const f = pickOne(facil);
  if (f) selected.push(f);
  const n = pickOne(normal.filter(w => !selected.includes(w)));
  if (n) selected.push(n);
  const d = pickOne(dificil.filter(w => !selected.includes(w)));
  if (d) selected.push(d);

  // Fill up if needed
  while (selected.length < count) {
    const fallback = pool[Math.floor(Math.random() * pool.length)];
    if (!selected.includes(fallback)) {
      selected.push(fallback);
    }
  }

  return selected.slice(0, count);
}
