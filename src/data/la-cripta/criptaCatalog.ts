/**
 * Authoritative helper to pick 3 distinct dungeon IDs from the 20-dungeon registry.
 */
export function selectThreeDistinctDungeons(
  seedInput?: number
): [CriptaDungeonId, CriptaDungeonId, CriptaDungeonId] {
  const pool = [...ALL_CRIPTA_DUNGEON_IDS];
  let s = seedInput ?? Math.floor(Math.random() * 2147483647);

  const nextRand = () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;
  };

  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(nextRand() * (i + 1));
    const tmp = pool[i];
    pool[i] = pool[j];
    pool[j] = tmp;
  }

  return [pool[0], pool[1], pool[2]];
}

/**
 * Generates the initial Phase-1 arrival node structure for the selected dungeon.
 * Ready to be extended in Phase 2+ with full procedural floor graphs.
 */
export function generatePhase1ArrivalNodes(dungeonId: CriptaDungeonId): CriptaRoomNode[] {
  const dungeon = CRIPTA_DUNGEONS_REGISTRY[dungeonId];
  if (!dungeon) {
    throw new Error(`Mazmorra desconocida: ${String(dungeonId)}`);
  }
  const formatRoomLabel = (slug: string) =>
    slug
      .split('_')
      .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
      .join(' ');

  const roomA = dungeon.roomPool[0] || 'galeria_interior';
  const roomB = dungeon.roomPool[1] || 'cripta_lateral';

  return [
    {
      id: `node_floor1_entrance_${dungeonId}`,
      type: 'ENTRANCE',
      floor: 1,
      depth: 0,
      title: `Umbral de ${dungeon.name}`,
      connections: ['node_floor1_chamber_a', 'node_floor1_chamber_b'],
      contentId: `${dungeonId}_arrival`,
      revealed: true,
      visited: true,
      resolved: true,
    },
    {
      id: 'node_floor1_chamber_a',
      type: 'COMBAT',
      floor: 1,
      depth: 1,
      title: formatRoomLabel(roomA),
      connections: [],
      contentId: roomA,
      revealed: true,
      visited: false,
      resolved: false,
    },
    {
      id: 'node_floor1_chamber_b',
      type: 'EVENT',
      floor: 1,
      depth: 1,
      title: formatRoomLabel(roomB),
      connections: [],
      contentId: roomB,
      revealed: true,
      visited: false,
      resolved: false,
    },
  ];
}

