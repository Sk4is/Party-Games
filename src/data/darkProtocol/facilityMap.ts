/**
 * AUTHORED SINGLE ROOM COORDINATE SYSTEM HELPERS
 * Normalized source coordinates: 0.0 .. 1.0 (0,0 = top-left, 1,1 = bottom-right of original PNG)
 */
export function roomToWorldX(normX: number): number {
  return normX * SOURCE_ROOM_WIDTH;
}

export function roomToWorldY(normY: number): number {
  return normY * SOURCE_ROOM_HEIGHT;
}

export function worldToRoomNormX(worldX: number): number {
  return Math.max(0, Math.min(1, worldX / SOURCE_ROOM_WIDTH));
}

export function worldToRoomNormY(worldY: number): number {
  return Math.max(0, Math.min(1, worldY / SOURCE_ROOM_HEIGHT));
}

